const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {JSDOM}=require('jsdom');
const root=path.resolve(__dirname,'../frontend');
const dom=new JSDOM(fs.readFileSync(path.join(root,'index.html'),'utf8'),{url:'http://localhost',runScripts:'outside-only'});
const w=dom.window;w.setInterval=()=>0;w.setTimeout=()=>0;
const ctx=dom.getInternalVMContext(),run=s=>new vm.Script(s).runInContext(ctx);
for(const name of ['ui.js','summary-format.js','desktop.js','modern.js','summary-stream.js','recording-history.js','recording-dock.js'])run(fs.readFileSync(path.join(root,name),'utf8'));
run("meetings.push({id:'test',title:'Test',when:'today',rows:[[0,'Test transcript']],summary:null});state.selected='test';state.page='notes';render();selectNoteTab('summary');");
assert.ok(w.document.querySelector('.summary-view'));
assert.equal(w.document.querySelector('#recording-dock').hidden,true);
assert.equal(w.document.querySelector('#meeting-context'),null);
run("window.sent=0;generateRealSummary=()=>{window.sent++;};");
const input=w.document.querySelector('#summary-instructions');input.value='Ringkas';
input.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true}));
assert.equal(w.sent,1);
input.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Enter',shiftKey:true,bubbles:true,cancelable:true}));
input.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Enter',isComposing:true,bubbles:true,cancelable:true}));
assert.equal(w.sent,1);
run("selectNoteTab('transcript')");assert.equal(input.value,'');assert.equal(w.document.querySelector('#recording-dock').hidden,false);
run("selectNoteTab('summary');getMeeting().instructions='draft';state.page='home';render();state.page='notes';render();");
assert.equal(w.document.querySelector('#summary-instructions').value,'');
run("engine.deviceChecked=true;showWizard();");
assert.equal(w.document.querySelectorAll('.wizard-field-group').length,2);
assert.equal(w.document.querySelectorAll('#wizard-model').length,1);
assert.ok(w.document.querySelector('#wizard-install'));
console.log('PASS: summary view, dock visibility, Enter/Shift+Enter/IME, draft reset and wizard structure');
(async()=>{
 run("document.getElementById('setup-wizard').remove();engine.ready=true;engine.modelReady=true;engine.state='idle';engine.selectedSpeaker={index:0};state.noteTab='summary';state.page='notes';render();window.starts=0;api=async()=>{window.starts++;return {session:'new-recording'};};");
 await Promise.all([run('startRecording()'),run('startRecording()')]);
 assert.equal(w.starts,1,'double click must not create two recordings');
 assert.equal(run('state.noteTab'),'transcript');
 assert.equal(run('state.selected'),'new-recording');
 assert.equal(w.document.querySelector('#panel-transcript').hidden,false);
 assert.equal(w.document.querySelector('#recording-dock').hidden,false);
 run("state.recording=false;engine.state='idle';state.page='home';render();api=async()=>{throw Error('Start failed');};");
 await run('startRecording()');
 assert.equal(run('state.page'),'home','failed start must not open a fake recording');
 assert.equal(run('state.recordStarting'),false);
 console.log('PASS: Record opens new transcript from summary, double-click guard and failed-start recovery');
 dom.window.close();
})().catch(error=>{console.error(error);dom.window.close();process.exitCode=1;});
